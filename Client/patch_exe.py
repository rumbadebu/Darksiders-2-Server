"""
Patch Darksiders2.exe for the local server:

  1. Replaces the embedded 'THQ Connect Root CA' certificate with our local CA
     (so the game trusts our HTTPS server).
  2. Replaces the two embedded '*.thqconnect.com' leaf certificates with our
     server certificate (in case the game pins the expected peer cert).
  3. Rewrites the GDS hostname 'ds2.gds.thqconnect.com' -> 'gds.thqconnect.com'
     so the wildcard CN of our server cert covers it.

Usage:
    python patch_exe.py --exe <exe-file-or-folder> --cert-dir <cert-directory>

The script copies the input exe into an `out/` subdirectory of the current
working directory, creates `out/Darksiders2.exe.orig` as a pristine backup,
then patches `out/Darksiders2.exe` in place.

Set DS2_EXE_SHA256 to the expected SHA-256 of the original (unpatched)
Darksiders2.exe to verify the input before patching. If the hash does not
match, the script aborts.

Name redirection (s.thqconnect.com etc. -> 127.0.0.1) is NOT done here; it is
handled by the ws2_32.dll proxy shim (or optionally the hosts file).
"""
import argparse
import base64
import hashlib
import os
import re
import shutil
import sys

CERT_DIR = None          # set from --cert-dir
OUT_DIR = os.path.join(os.getcwd(), 'out')
EXE_OUT = os.path.join(OUT_DIR, 'Darksiders2.exe')
ORIG_OUT = os.path.join(OUT_DIR, 'Darksiders2.exe.orig')

PEM_RE = re.compile(rb'-----BEGIN CERTIFICATE-----.*?-----END CERTIFICATE-----', re.S)
KEY_RE = re.compile(rb'-----BEGIN RSA PRIVATE KEY-----.*?-----END RSA PRIVATE KEY-----', re.S)


def der_of(pem_block):
    body = b''.join(pem_block.split(b'\n')[1:-1])
    return base64.b64decode(body, validate=False)


def classify(pem_block):
    der = der_of(pem_block)
    if b'THQ Connect Root CA' in der:
        return 'root_ca'
    if b'THQ Connect Client CA' in der:
        return 'client_ca'
    if b'*.thqconnect.com' in der:
        return 'leaf'
    return 'unknown'


def pad_pem(pem_bytes, size):
    """Return exactly `size` bytes: PEM + newline padding."""
    if len(pem_bytes) > size:
        raise RuntimeError('PEM (%d bytes) does not fit slot (%d bytes)' % (len(pem_bytes), size))
    return pem_bytes + b'\n' * (size - len(pem_bytes))


def patch_host_string(data, old, new):
    """Replace NUL-terminated string `old` with shorter `new` + NUL padding."""
    needle = old + b'\x00'
    count = 0
    start = 0
    while True:
        idx = data.find(needle, start)
        if idx == -1:
            break
        repl = new + b'\x00' * (len(needle) - len(new))
        data = data[:idx] + repl + data[idx + len(needle):]
        start = idx + len(repl)
        count += 1
    return data, count


def resolve_exe_source(exe_arg):
    """Resolve --exe argument: can be a file path or a folder path.

    If a folder, looks for Darksiders2.exe.original, Darksiders2.exe, or
    Darksiders2.exe.patched inside it (in that order).
    """
    if os.path.isfile(exe_arg):
        return exe_arg
    if os.path.isdir(exe_arg):
        for name in ('Darksiders2.exe.original', 'Darksiders2.exe',
                     'Darksiders2.exe.patched'):
            cand = os.path.join(exe_arg, name)
            if os.path.isfile(cand):
                return cand
    print('ERROR: could not find a Darksiders2 exe in %r' % exe_arg)
    sys.exit(1)


def main():
    global CERT_DIR
    ap = argparse.ArgumentParser(
        description='Patch Darksiders2.exe for the local DS2 server')
    ap.add_argument('--exe', required=True,
                    help='Path to Darksiders2.exe file, or a folder containing it '
                         '(e.g. debug\\Darksiders2.exe.original)')
    ap.add_argument('--cert-dir', required=True,
                    help='Path to the certificate directory (the out/ folder '
                         'generated by cert-tools)')
    args = ap.parse_args()
    CERT_DIR = args.cert_dir
    if not os.path.isdir(CERT_DIR):
        print('ERROR: cert directory not found: %s' % CERT_DIR)
        sys.exit(1)
    if not os.path.exists(os.path.join(CERT_DIR, 'ca.pem')):
        print('ERROR: ca.pem not found in %s - run the cert-tools first' % CERT_DIR)
        sys.exit(1)

    os.makedirs(OUT_DIR, exist_ok=True)

    # --- resolve input exe, verify, copy into out/ ---
    exe_src = resolve_exe_source(args.exe)
    print('source exe: %s' % exe_src)
    exe_data = open(exe_src, 'rb').read()
    print('source size: %d bytes' % len(exe_data))

    expected_hash = os.environ.get('DS2_EXE_SHA256')
    if expected_hash:
        actual_hash = hashlib.sha256(exe_data).hexdigest()
        if actual_hash.lower() != expected_hash.lower():
            print('ERROR: Darksiders2.exe hash mismatch!')
            print('  expected: %s' % expected_hash)
            print('  actual:   %s' % actual_hash)
            print('  Set DS2_EXE_SHA256 to the correct original hash, or unset to skip.')
            sys.exit(1)
        print('hash verified: %s' % actual_hash)

    if b'Local DS2' in exe_data:
        print('ERROR: input exe appears already patched ("Local DS2" marker found).')
        print('Refusing to double-patch. Use a pristine original exe.')
        sys.exit(1)

    shutil.copy2(exe_src, EXE_OUT)
    shutil.copy2(exe_src, ORIG_OUT)
    print('copied to: %s' % EXE_OUT)
    print('backup created: %s' % ORIG_OUT)

    # --- certificates from --cert-dir ---
    ca_pem = open(os.path.join(CERT_DIR, 'ca.pem'), 'rb').read().strip()
    srv_pem = open(os.path.join(CERT_DIR, 'server.crt'), 'rb').read().strip()

    # local client-auth kit (mutual TLS) - optional inputs
    cli_pem = ''
    cli_key = ''
    cli_crt_path = os.path.join(CERT_DIR, 'ds2_client.crt')
    cli_key_path = os.path.join(CERT_DIR, 'ds2_client.key')
    if os.path.exists(cli_crt_path):
        cli_pem = open(cli_crt_path, 'rb').read().strip()
    if os.path.exists(cli_key_path):
        cli_key = open(cli_key_path, 'rb').read().strip()
    if cli_pem and cli_key:
        print('client kit found: installing into exe slots (mutual TLS)')
    else:
        print('no client kit found (ds2_client.crt/.key): client slots untouched')

    # --- leaf-clone mapping (service-cert identity emulation) ---
    # Game chain-verifies against the Root CA slot (proven: self-signed clone
    # -> unknown_ca; Root-signed cert -> full mTLS) AND runs a post-handshake
    # identity check against the leaf slots (proven: clean close on a valid
    # chain with a CN-only subject). leaf{n}_ca.pem satisfies both: original
    # subject DN + serial, signed by our Root CA, byte-embedded in the slot.
    leaf_clones = {}
    tools_dir = (CERT_DIR if os.path.exists(os.path.join(CERT_DIR, 'leaf1_orig.der'))
                 else os.path.dirname(CERT_DIR))
    for _nm in ('leaf1', 'leaf2'):
        _cp = os.path.join(CERT_DIR, '%s_ca.pem' % _nm)
        _lbl = '%s_ca (Root-signed original identity)' % _nm
        if not os.path.exists(_cp):
            _cp = os.path.join(CERT_DIR, '%s_clone.pem' % _nm)
            _lbl = '%s clone (self-signed identity)' % _nm
        _op = os.path.join(tools_dir, '%s_orig.der' % _nm)
        if os.path.exists(_cp) and os.path.exists(_op):
            try:
                from cryptography import x509 as _x509
                _orig = _x509.load_der_x509_certificate(open(_op, 'rb').read())
                leaf_clones[_orig.serial_number] = (_nm, _lbl, open(_cp, 'rb').read().strip())
            except Exception as e:
                print('WARNING: could not map %s clone: %r' % (_nm, e))
    print('leaf slots mapped by serial: %s'
          % (', '.join('%s=0x%X' % (nm, sn)
                       for sn, (nm, _lb, _p) in leaf_clones.items())
             or 'none'))

    # source exe already copied to out/ and hash-verified above
    src = exe_data
    print('source: %s (%d bytes)' % (os.path.basename(exe_src), len(src)))

    data = src
    stats = {'root_ca': 0, 'leaf': 0, 'client_ca': 0}
    orig_leaf_blocks = []   # exact bytes of the original leaf certs (verify: must vanish)

    # --- certificate slot replacement ---
    out = bytearray()
    last = 0
    for m in PEM_RE.finditer(src):
        block = m.group()
        kind = classify(block)
        out += src[last:m.start()]
        if kind == 'root_ca':
            out += pad_pem(ca_pem, len(block))
            stats['root_ca'] += 1
            print('root CA slot @0x%06x (%d bytes) -> local CA (%d bytes)'
                  % (m.start(), len(block), len(ca_pem)))
        elif kind == 'leaf':
            orig_leaf_blocks.append(block)
            repl, label = srv_pem, 'server.crt'
            _hit = None
            try:
                from cryptography import x509 as _x509
                slot_cert = _x509.load_pem_x509_certificate(block)
                _hit = leaf_clones.get(slot_cert.serial_number)
                if _hit:
                    repl, label = _hit[2], _hit[1]
            except Exception:
                pass
            padded = pad_pem(repl, len(block))
            out += padded
            if _hit:
                # exact slot bytes for the server to serve (byte-identical
                # to what the exe embeds - covers exact-byte pin checks)
                with open(os.path.join(CERT_DIR, '%s_slot.pem' % _hit[0]), 'wb') as _f:
                    _f.write(padded)
            stats['leaf'] += 1
            print('leaf cert slot @0x%06x (%d bytes) -> %s (%d bytes)'
                  % (m.start(), len(block), label, len(repl)))
        elif kind == 'client_ca' and cli_pem:
            out += pad_pem(cli_pem, len(block))
            stats['client_ca'] += 1
            print('client cert slot @0x%06x (%d bytes) -> local DS2 client cert (%d bytes)'
                  % (m.start(), len(block), len(cli_pem)))
        else:
            out += block  # unknown / client-without-kit: untouched
            if kind == 'client_ca':
                stats['client_ca'] += 1
                print('client cert slot @0x%06x (%d bytes) left %s'
                      % (m.start(), len(block),
                         'as-is (no kit)' if not cli_pem else 'as-is'))
        last = m.end()
    out += src[last:]
    data = bytes(out)

    # --- client RSA private key slot replacement (mutual TLS) ---
    kstats = 0
    if cli_key:
        out2 = bytearray()
        last = 0
        for m in KEY_RE.finditer(data):
            out2 += data[last:m.start()]
            out2 += pad_pem(cli_key, len(m.group()))
            print('client key slot @0x%06x (%d bytes) -> local client key (%d bytes)'
                  % (m.start(), len(m.group()), len(cli_key)))
            kstats += 1
            last = m.end()
        out2 += data[last:]
        data = bytes(out2)
    if kstats != 1:
        print('WARNING: expected exactly 1 client RSA key slot replaced, got %d' % kstats)

    if stats['root_ca'] != 1:
        print('ERROR: expected exactly 1 root CA slot, found %d' % stats['root_ca'])
        sys.exit(1)
    if stats['leaf'] < 1:
        print('ERROR: no leaf *.thqconnect.com cert slots found')
        sys.exit(1)
    print('client CA slots left untouched: %d' % stats['client_ca'])

    # --- GDS hostname rewrite (wildcard CN covers single-label subdomains) ---
    # the stored string carries a trailing dot: 'ds2.gds.thqconnect.com.'
    data, n = patch_host_string(data, b'ds2.gds.thqconnect.com.', b'gds.thqconnect.com')
    if n == 0:
        data, n = patch_host_string(data, b'ds2.gds.thqconnect.com', b'gds.thqconnect.com')
    print('GDS host ds2.gds.thqconnect.com -> gds.thqconnect.com: %d occurrence(s)' % n)

    with open(EXE_OUT, 'wb') as f:
        f.write(data)
    print('written: %s (%d bytes)' % (EXE_OUT, len(data)))

    # --- verification ---
    chk = open(EXE_OUT, 'rb').read()
    ok = True
    if b'THQ Connect Root CA' in b''.join(der_of(m.group()) for m in PEM_RE.finditer(chk)):
        pass  # our CA also contains that CN text; verify by serial instead
    for ob in orig_leaf_blocks:
        if ob in chk:
            print('VERIFY FAIL: original THQ leaf cert bytes still present '
                  '(%d-byte block)' % len(ob))
            ok = False
    if re.search(rb'ds2\.gds\.thqconnect\.com\.?\x00', chk):
        print('VERIFY FAIL: old GDS hostname still present')
        ok = False
    if b'gds.thqconnect.com\x00' not in chk:
        print('VERIFY FAIL: new GDS hostname missing')
        ok = False
    if cli_pem and cli_pem not in chk:
        print('VERIFY FAIL: local client cert not embedded')
        ok = False
    if cli_key and cli_key not in chk:
        print('VERIFY FAIL: local client key not embedded')
        ok = False
    for _sn, (_nm, _lbl, _pem) in leaf_clones.items():
        if _pem not in chk:
            print('VERIFY FAIL: %s clone not embedded' % _nm)
            ok = False
    print('verification: %s' % ('OK' if ok else 'FAILED'))
    sys.exit(0 if ok else 1)


if __name__ == '__main__':
    main()